def s44(n):
    lk, b = ST['look'], ST['look_best']
    ca = ST['cache']
    o = [sec('s44', n, '流式：前瞻、分块与状态', '深入',
             lede='流式系统的每一个旋钮——前瞻帧数、chunk 大小、缓存长度——'
                  '都同时是延迟旋钮和精度旋钮。这一节把三条曲线量出来。',
             tldr='前瞻不是越多越好：1 帧 %.1f%%、%d 帧 %.2f%%、20 帧又回到 %.1f%%。'
                  '最优 %d 帧 = %.0f ms，正好是一个音素的长度。'
                  '两端各有一个不同的失效机制。'
                  % (lk[0]['ter'], b['look'], b['ter'], lk[-1]['ter'],
                     b['look'], b['lat_ms']))]

    o.append('<h3>① 延迟是加起来的，不是算出来的</h3>')
    o.append(fml('端到端延迟预算', 'latency',
                 [('T_chunk', '攒够一块的时间'), ('T_look', '前瞻要等的未来帧'),
                  ('T_compute', '真正的计算时间'),
                  ('T_endpoint', '判定"说完了"要等的静音')]))
    o.append(why('大多数团队优化的是 T_compute，但它通常是四项里最小的一项。'
                 '真正的大头是 T_chunk + T_look（结构决定，改不了除非改模型）'
                 '和 T_endpoint（策略决定，通常 300–700 ms）。'
                 '先做预算分解，再决定优化谁。'))

    o.append('<h3>② 前瞻：两端都差，中间有个坑</h3>')
    o.append(fig('stream', '左：前瞻帧数与错误率。右：chunk 大小对状态缓存的影响。'))
    o.append(table(['前瞻帧数', '#附加延迟', '#TER', '相对整句解码'], [
        ('#%d' % r['look'], '#%.0f ms' % r['lat_ms'], '#%.2f%%' % r['ter'],
         '#%+.2f' % r['gap']) for r in lk], cls='dp'))
    o.append(ex('两端的失效机制不一样',
                '<p><strong>前瞻太短</strong>（1–2 帧）：声学证据还没攒够就得定。'
                '一个音素的证据要好几帧才完整，只看一帧等于在猜。</p>'
                '<p><strong>前瞻太长</strong>（12–20 帧）：解码点一直往后拖。'
                '每往后拖一帧，前面已经定下来的假设就多一次被新观测推翻的机会，'
                '而流式解码是<strong>不能回头改</strong>的——一旦吐字就算数了。</p>'
                '<p>所以最优点出现在"证据刚够用"的地方：%d 帧 × %.0f ms = <strong>%.0f ms</strong>，'
                '量级上正是一个音素的长度。这不是巧合，是这条曲线的物理含义。</p>'
                % (b['look'], ST['look'][0]['lat_ms'], b['lat_ms'])))
    o.append(note('注意 gap 那一列会变成负数',
                  '<p>前瞻 %d 帧时 TER 比整句解码（%.2f%%）还低 %.2f 个点。'
                  '这不是流式比整句强，是这个合成任务的整句解码也会被远处的无关证据干扰。'
                  '真实系统里整句解码几乎总是更好，'
                  '但"流式最优点附近和整句差距很小"这个结论是普遍的。</p>'
                  % (b['look'], ST['look_full'], -b['gap'])))

    o.append('<h3>③ 状态缓存：延迟和显存是同一个旋钮的两端</h3>')
    o.append(fml('编码器状态缓存的大小', 'cache',
                 [('N_layer', '层数'), ('T_hist', '每层要留的历史帧'),
                  ('d', '隐层维度'), ('B', '并发路数')]))
    o.append(table(['chunk 帧数', '#分块延迟', '#每层缓存', '#单路合计', '#100 路'], [
        ('#%d' % r['chunk'], '#%.2f s' % (r['lat_ms'] / 1000),
         '#%.0f KB' % r['per_layer_kb'], '#%.2f MB' % r['total_mb'],
         '#%.0f MB' % (r['total_mb'] * 100)) for r in ca], cls='dp'))
    o.append(trap('并发才是端侧/网关侧的真约束',
                  '<p>单路 %.2f MB 听起来无所谓，但缓存是<strong>常驻</strong>的——'
                  '每一路连接只要还开着就一直占着。100 路并发就是 %.0f MB，'
                  '而且这部分显存不能和计算峰值复用。</p>'
                  '<p>常见的误判是拿单路测出来的显存乘以并发数去估容量，'
                  '却忘了计算峰值是<strong>错峰</strong>的而缓存不是。'
                  '缓存要按并发数满打满算，计算峰值可以按实际同时在算的路数估。</p>'
                  % (ca[2]['total_mb'], ST['cache_100'])))
    o.append('<p>算力与功耗怎么从 MAC 数换算到毫瓦，' + SV + '（18 节）按常驻场景算过一遍，'
             '这里不重复。</p>')
    o.append(q([
        ('前瞻帧数是不是越多越好？为什么？',
         '<p>不是。实测 1 帧 %.1f%%、%d 帧 %.2f%%、20 帧 %.1f%%，是个 U 形。'
          '太短是证据不够，太长是解码点后拖、已定的假设被推翻的机会变多。'
          '最优 %d 帧 = %.0f ms，约一个音素的长度。</p>'
          % (lk[0]['ter'], b['look'], b['ter'], lk[-1]['ter'], b['look'], b['lat_ms'])),
        ('端到端延迟里最容易被忽略的一项是什么？',
         '<p>T_endpoint——判定"说完了"要等的静音，通常 300–700 ms，'
          '往往比 T_compute 大一个量级。优化计算之前先做预算分解。</p>'),
        ('100 路并发的流式 ASR，状态缓存要按什么估？',
         '<p>按满打满算：缓存是常驻的，不能错峰复用。chunk=16 时单路 %.2f MB，'
          '100 路就是 %.0f MB。计算峰值倒是可以按实际同时在算的路数估。</p>'
          % (ca[2]['total_mb'], ST['cache_100'])),
    ]))
    o.append('</section>')
    return ''.join(o)


