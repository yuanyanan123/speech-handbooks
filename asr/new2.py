def s43(n):
    f = DE['fusion']
    sh, dr, il = DE['shallow_best'], DE['dr_best'], DE['ilme_best']
    o = [sec('s43', n, '语言模型融合与内部语言模型', '深入',
             lede='端到端模型在训练时把文本也一起学了，所以它自带一个语言模型。'
                  '往上加外部 LM 之前，得先知道里面那个有多强——否则语言先验会被算两遍。',
             tldr='同一批句子：不融合 %.2f%%，浅融合最好 %.2f%%，'
                  '而<strong>减掉内部 LM 之后是 %.2f%%</strong>——'
                  '比浅融合又少了近一半的错。融合不是默认该开的开关，'
                  'LM 和目标域不沾边时最优权重是 0。'
                  % (f['none'], f['shallow'], f['ilme']))]

    o.append('<h3>① 内部语言模型是什么</h3>')
    o.append('<p>RNN-T 的预测网络、AED 的解码器，输入都是"已经输出的标签"。'
             '训练时它们见过的所有文本，都变成了参数里的一个隐式语言模型。'
             '把声学证据拿掉——让联合网络只看预测网络那一路——剩下的就是它。</p>')
    o.append(fml('内部语言模型的估计', 'ilm',
                 [('置零', '把声学输入换成零或训练集均值'),
                  ('剩下的', '只由已输出的历史决定的那部分分布')]))
    o.append(note('这本书为什么能验证这件事',
                  '<p>真实模型里，内部 LM 的强度是未知的，只能估。'
                  '本节的模型是<strong>解析构造</strong>的：'
                  '声学得分定义成 <code>A[u] + τ · logP_src(y|hist)</code>，'
                  'τ=%.2f 是我自己设的。所以"减掉内部 LM"到底该减多少、'
                  '减对了会怎样，是有标准答案的。</p>'
                  '<p>代价：这不是真实系统上的数。可比的是三种方法的<strong>相对关系</strong>'
                  '和最优权重的移动方向。</p>' % f['tau']))

    o.append('<h3>② 三种做法</h3>')
    o.append(fml('浅融合、密度比、ILME', 'fusion',
                 [('λ', '加外部 LM 的权重'),
                  ('γ', '减内部 / 源域 LM 的权重'),
                  ('三行的区别', '减的是谁：不减 / 另训的源域 LM / 模型自己')]))
    o.append(fig('fusion', '左：三种做法的权重扫描。右：外部 LM 越贴合目标域，'
                           '最优融合权重才越大。'))
    o.append(table(['做法', '#最优权重', '#TER', '相对不融合', '代价'], [
        ('不融合', '#—', '#%.2f%%' % f['none'], '#—', '—'),
        ('浅融合', '#λ=%.1f' % sh['lam'], '#%.2f%%' % sh['ter'],
         '#−%.0f%%' % ((f['none'] - sh['ter']) / f['none'] * 100),
         '最简单，只要一个外部 LM'),
        ('密度比', '#γ=%.2f' % dr['gam'], '#<strong>%.2f%%</strong>' % dr['ter'],
         '#−%.0f%%' % ((f['none'] - dr['ter']) / f['none'] * 100),
         '要额外训一个源域 LM'),
        ('ILME', '#γ=%.1f' % il['gam'], '#<strong>%.2f%%</strong>' % il['ter'],
         '#−%.0f%%' % ((f['none'] - il['ter']) / f['none'] * 100),
         '每步多一次预测网络前向'),
    ], cls='dp'))
    o.append(why('浅融合的曲线是个 U：λ 从 0 加到 %.1f 时变好，再加就变坏，'
                 'λ=1.0 时（%.2f%%）已经比不融合还差。'
                 '因为语言先验被算了两遍——一遍在声学模型的参数里，一遍在外部 LM 里。'
                 '减内部 LM 的两种做法没有这个上限问题，曲线底部平坦得多。'
                 % (sh['lam'], [r for r in DE['shallow'] if r['lam'] == 1.0][0]['ter'])))

    o.append('<h3>③ 融合不是默认该开的开关</h3>')
    o.append(ex('让外部 LM 从"完全不沾边"渐变到"完全贴合"',
                '<p>把外部 LM 的训练文本按比例从源域混到目标域，每一档扫一遍 λ：</p>'
                + table(['LM 贴合目标域的程度', '#最优 λ', '#该档最好的 TER'],
                        [('#%.0f%%' % (r['mix'] * 100), '#%.1f' % r['best_lam'],
                          '#%.2f%%' % r['ter']) for r in DE['drift']], cls='dp')
                + '<p><strong>前三档的最优 λ 都是 0</strong>：外部 LM 只要不够贴合，'
                  '加任何权重都是净损失。到 75%% 贴合时最优 λ 才抬到 %.1f。</p>'
                  '<p>这条曲线解释了一个常见现象：同一个 LM，在 A 项目上加了有效，'
                  '搬到 B 项目上加了变差。不是 LM 不好，是域变了。</p>'
                % DE['drift'][-2]['best_lam']))
    o.append(trap('调 λ 时最容易犯的三个错',
                  '<p><strong>① 在训练集的同分布数据上调 λ。</strong>'
                  '那里内部 LM 和外部 LM 高度一致，λ 怎么调都差不多，'
                  '搬到线上就崩。要在目标域的开发集上调。</p>'
                  '<p><strong>② 把 λ 和 beam 一起调。</strong>'
                  '两者耦合：λ 大时错误路径的分数变化剧烈，需要的 beam 也不同。'
                  '先固定 beam 调 λ，再回头验 beam。</p>'
                  '<p><strong>③ 忘了长度惩罚。</strong>加了外部 LM 之后，'
                  '每多一个词就多一份 −log P，模型会倾向输出更短的句子。'
                  '删除错误会涨。要配一个词插入奖励。</p>'))
    o.append(q([
        ('为什么端到端模型加外部 LM，λ 大了反而变差？',
         '<p>因为模型自带内部语言模型（训练文本学进参数了）。'
          '直接加外部 LM 等于把语言先验算了两遍。实测 λ=1.0 时 %.2f%%，比不融合的 %.2f%% 还差。</p>'
          % ([r for r in DE['shallow'] if r['lam'] == 1.0][0]['ter'], f['none'])),
        ('密度比和 ILME 的区别是什么？',
         '<p>都是"减掉内部 LM"，区别在减的是谁：密度比减一个<strong>在源域文本上另训的 LM</strong>'
          '（需要额外训练，但便宜）；ILME 减的是<strong>从模型自己身上估出来的</strong>'
          '（把声学输入置零跑一遍预测网络，每步多一次前向）。本实验里两者几乎打平'
          '（%.2f%% vs %.2f%%）。</p>' % (dr['ter'], il['ter'])),
        ('外部 LM 和目标域不沾边时，最优 λ 是多少？',
         '<p>0。实测贴合度 0%、25%、50% 三档的最优 λ 全是 0——'
          '加任何权重都是净损失。融合不是默认该开的开关。</p>'),
    ]))
    o.append('</section>')
    return ''.join(o)


