    o.append('<p>CTC 解码不能简单取每帧最大值再合并（会漏掉"总概率更大但单帧不是最大"的序列）。前缀束搜索维护<strong>每个候选前缀的两个概率</strong>：以空白结尾的概率 p<sub>b</sub> 与以非空白结尾的概率 p<sub>nb</sub>，因为二者在遇到下一个符号时的转移规则不同：</p>')
