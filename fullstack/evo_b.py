    o.append('<p>读递推：前缀 ℓ 后接一个与末尾相同的字符 c，只有当前缀<strong>以空白结尾</strong>时才产生新字符（否则被合并为重复）；后接不同字符则两种结尾都可以。外接语言模型时，在前缀被扩展出新字符的那一步加上语言模型的分数。</p>')
    o.append(h4('8.4 MBR：从"最大后验"到"最小期望错误"'))
    o.append('<p>MAP 解码选后验最大的序列，对应的是 0/1 损失（"完全对才算对"）。但评价指标是编辑距离。如果候选里有三条互相相似但每条后验都不大的假设，和一条后验略高但孤立的假设，MAP 选孤立的那条；而最小贝叶斯风险（MBR）会选"离所有候选的加权平均距离最小"的那条，即<strong>共识</strong>：</p>')
    o.append(fml('最小贝叶斯风险解码', 'mbr', [('𝒩', 'N-best 假设集合'), ('L', '损失函数，编辑距离')]))
