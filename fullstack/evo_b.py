    o.append('<p>代价：每一步要一次前向与对整个词表的 softmax，难以像 n-gram 那样直接编进静态图；所以常用于<strong>重打分</strong>或<strong>浅融合</strong>。</p>')
    o.append(h4('8.2 内部语言模型的估计与减除'))
    o.append('<p>RNN-T 的预测网络与注意力解码器，会学到训练转写文本的统计。外接语言模型时，这个先验被<strong>重复计数</strong>，导致输出偏向训练文本域、在目标域上变差。'
             '修正办法是估计这个内部语言模型（ILM）并减掉。最常见的估计法：把声学上下文抹掉（置零或取平均），只留下解码器对文本的预测：</p>')
